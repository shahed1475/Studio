"""A readable snapshot of the settings that live only on the server (not in git): `llm.json`, `autopilot.json`, `agent.json`, `niche.json`, and the small
files in `data/` that decide behaviour. Secrets are hidden. `python run.py state` prints it as Markdown, so a rebuilt server can be set up the same way."""
import json
from pathlib import Path

import config

FILES = ("llm.json", "autopilot.json", "agent.json", "niche.json", "data/titletest.json", "data/playlists.json", "data/youtube_login.json",
         "data/worker_state.json")
SECRET = ("key", "token", "secret", "password", "hash")
LONG = 400  # characters: longer values (a niche brief, a list of ideas) are cut


def _hide(v):
    if isinstance(v, dict):
        return {k: ("[hidden]" if any(s in k.lower() for s in SECRET) else _hide(x)) for k, x in v.items()}
    if isinstance(v, list):
        return [_hide(x) for x in v]
    if isinstance(v, str) and len(v) > LONG:
        return v[:LONG] + "..."
    return v


def snapshot(root: Path | None = None) -> dict:
    root = root or config.ROOT
    out = {}
    for name in FILES:
        try:
            out[name] = _hide(json.loads((root / name).read_text()))
        except (OSError, ValueError):
            continue
    return out


def markdown(snap: dict) -> str:
    parts = ["# Server-only settings", "",
             "These files live on the server and are not in git. Secrets are hidden. Generated by `python run.py state`; copy a value back by hand to rebuild a server.", ""]
    for name, value in snap.items():
        parts += [f"## {name}", "", "```json", json.dumps(value, indent=2, ensure_ascii=False), "```", ""]
    return "\n".join(parts)
